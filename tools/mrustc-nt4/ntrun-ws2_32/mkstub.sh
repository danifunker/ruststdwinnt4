#!/bin/sh
# mkstub.sh CPU EXE DIR: a stand-in WS2_32.DLL in DIR for running EXE under ntrun, which has
# no sockets and no WS2_32.DLL (std imports it in every program). WSAStartup and WSACleanup
# succeed; every other function EXE imports from it fails with WSAENETDOWN, so a program's
# networking gets errors instead of the program not loading. For the tests only: nothing of
# it goes into a program. Runs inside tenox7/ntsdk.
cpu=$1 exe=$2 d=$3
here=$(cd "$(dirname "$0")" && pwd)
ntsdk nt40 "$cpu" link -dump -imports "$exe" > "$d/imports-$cpu.txt" 2>&1 || { cat "$d/imports-$cpu.txt"; exit 1; }
# The functions in WS2_32.dll's section: "  hint  name" lines, or "Ordinal  n"
tr -d '\r' < "$d/imports-$cpu.txt" | awk '
     /^ +[A-Za-z0-9_]+\.dll *$/ { ws = (tolower($1) == "ws2_32.dll"); next }
     ws && /Ordinal +[0-9]+/ { for(i=1;i<=NF;i++) if($i=="Ordinal") print "#" $(i+1); next }
     ws && /^ +[0-9A-Fa-f]+ +[A-Za-z_][A-Za-z0-9_]* *$/ { print $2 }' | sort -u > "$d/ws2_32-$cpu.names"
[ -s "$d/ws2_32-$cpu.names" ] || { echo "mkstub: no WS2_32 imports found in:"; head -40 "$d/imports-$cpu.txt"; exit 1; }
{
    echo '/* Generated by mkstub.sh: a stand-in WS2_32.DLL for ntrun (see there). */'
    echo '__declspec(dllimport) void __stdcall SetLastError(unsigned long);'
    echo 'static long fail(void) { SetLastError(10050); return -1; } /* WSAENETDOWN, SOCKET_ERROR */'
    echo 'int __stdcall stub_WSAStartup(unsigned short v, void* data) { char* p = (char*)data; int i; for(i = 0; i < 400; i++) p[i] = 0; *(unsigned short*)p = v; *(unsigned short*)(p + 2) = v; return 0; }'
    echo 'int __stdcall stub_WSACleanup(void) { return 0; }'
    echo 'static int last_error = 10050;'
    echo 'int __stdcall stub_WSAGetLastError(void) { return last_error; }'
    echo 'void __stdcall stub_WSASetLastError(int e) { last_error = e; }'
    while read -r n; do
        case "$n" in
        WSAStartup|WSACleanup|WSAGetLastError|WSASetLastError|'#115'|'#116'|'#111'|'#112') ;;
        '#'*) echo "long __stdcall stub_ord${n#\#}(void) { return fail(); }" ;;
        # the ones returning a pointer give NULL
        gethostby*|getservby*|getprotoby*|inet_ntoa) echo "void* __stdcall stub_$n(void) { fail(); return 0; }" ;;
        *) echo "long __stdcall stub_$n(void) { return fail(); }" ;;
        esac
    done < "$d/ws2_32-$cpu.names"
} > "$d/ws2_32-$cpu.c"
{
    echo 'LIBRARY WS2_32'
    echo 'EXPORTS'
    echo '    WSAStartup = stub_WSAStartup @115'
    echo '    WSACleanup = stub_WSACleanup @116'
    echo '    WSAGetLastError = stub_WSAGetLastError @111'
    echo '    WSASetLastError = stub_WSASetLastError @112'
    while read -r n; do
        case "$n" in
        WSAStartup|WSACleanup|WSAGetLastError|WSASetLastError|'#115'|'#116'|'#111'|'#112') ;;
        '#'*) echo "    stub_ord${n#\#} @${n#\#} NONAME" ;;
        *) echo "    $n = stub_$n" ;;
        esac
    done < "$d/ws2_32-$cpu.names"
} > "$d/ws2_32-$cpu.def"
( cd "$d" && ntsdk nt40 "$cpu" cl -nologo -LD -Fews2_32.dll ws2_32-$cpu.c kernel32.lib -link -def:ws2_32-$cpu.def ) \
    > "$d/ws2_32-build-$cpu.log" 2>&1 || { cat "$d/ws2_32-build-$cpu.log"; exit 1; }
echo "stand-in WS2_32.DLL: $(wc -l < "$d/ws2_32-$cpu.names") functions"
