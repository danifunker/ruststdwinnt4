#!/bin/sh
# mkstub.sh CPU EXE DIR DLL: a stand-in DLL.DLL in DIR for running EXE under ntrun, which lacks
# some of NT's DLLs (no sockets, so no WS2_32; no USERENV) that std imports in every program.
# Every function EXE imports from it fails: for WS2_32 with WSAENETDOWN (WSAStartup and
# WSACleanup succeed, so networking gets errors instead of the program not loading), for any
# other DLL with ERROR_CALL_NOT_IMPLEMENTED and a result of 0. For the tests only: nothing of
# it goes into a program. Runs inside tenox7/ntsdk.
cpu=$1 exe=$2 d=$3 dll=$(echo "$4" | tr 'A-Z' 'a-z')
ntsdk nt40 "$cpu" link -dump -imports "$exe" > "$d/imports-$cpu.txt" 2>&1 || { cat "$d/imports-$cpu.txt"; exit 1; }
# The functions in the DLL's section ("  hint  name" lines, or "Ordinal  n"); the dumper's
# lines end in CR LF
tr -d '\r' < "$d/imports-$cpu.txt" | awk -v want="$dll.dll" '
     /^ +[A-Za-z0-9_]+\.dll *$/ { on = (tolower($1) == want); next }
     on && /Ordinal +[0-9]+/ { for(i=1;i<=NF;i++) if($i=="Ordinal") print "#" $(i+1); next }
     on && /^ +[0-9A-Fa-f]+ +[A-Za-z_][A-Za-z0-9_]* *$/ { print $2 }' | sort -u > "$d/$dll-$cpu.names"
[ -s "$d/$dll-$cpu.names" ] || { echo "mkstub: no $dll imports found in:"; head -40 "$d/imports-$cpu.txt"; exit 1; }
if [ "$dll" = ws2_32 ]; then err=10050 ret=-1 special='WSAStartup WSACleanup WSAGetLastError WSASetLastError'
else err=120 ret=0 special=; fi
is_special() { for s in $special; do [ "$1" = "$s" ] && return 0; done; return 1; }
{
    echo "/* Generated by mkstub.sh: a stand-in $dll.dll for ntrun (see there). */"
    echo '__declspec(dllimport) void __stdcall SetLastError(unsigned long);'
    echo "static long fail(void) { SetLastError($err); return $ret; }"
    if [ "$dll" = ws2_32 ]; then
        echo 'int __stdcall stub_WSAStartup(unsigned short v, void* data) { char* p = (char*)data; int i; for(i = 0; i < 400; i++) p[i] = 0; *(unsigned short*)p = v; *(unsigned short*)(p + 2) = v; return 0; }'
        echo 'int __stdcall stub_WSACleanup(void) { return 0; }'
        echo 'static int last_error = 10050;'
        echo 'int __stdcall stub_WSAGetLastError(void) { return last_error; }'
        echo 'void __stdcall stub_WSASetLastError(int e) { last_error = e; }'
    fi
    while read -r n; do
        is_special "$n" && continue
        case "$n" in
        '#'*) echo "long __stdcall stub_ord${n#\#}(void) { return fail(); }" ;;
        # the ones returning a pointer give NULL
        gethostby*|getservby*|getprotoby*|inet_ntoa) echo "void* __stdcall stub_$n(void) { fail(); return 0; }" ;;
        *) echo "long __stdcall stub_$n(void) { return fail(); }" ;;
        esac
    done < "$d/$dll-$cpu.names"
} > "$d/$dll-$cpu.c"
{
    echo "LIBRARY $(echo "$dll" | tr 'a-z' 'A-Z')"
    echo 'EXPORTS'
    if [ "$dll" = ws2_32 ]; then
        echo '    WSAStartup = stub_WSAStartup @115'
        echo '    WSACleanup = stub_WSACleanup @116'
        echo '    WSAGetLastError = stub_WSAGetLastError @111'
        echo '    WSASetLastError = stub_WSASetLastError @112'
    fi
    while read -r n; do
        is_special "$n" && continue
        case "$n" in
        '#'*) echo "    stub_ord${n#\#} @${n#\#} NONAME" ;;
        *) echo "    $n = stub_$n" ;;
        esac
    done < "$d/$dll-$cpu.names"
} > "$d/$dll-$cpu.def"
( cd "$d" && ntsdk nt40 "$cpu" cl -nologo -LD -Fe$dll.dll $dll-$cpu.c kernel32.lib -link -def:$dll-$cpu.def ) \
    > "$d/$dll-build-$cpu.log" 2>&1 || { cat "$d/$dll-build-$cpu.log"; exit 1; }
echo "stand-in $dll.dll: $(wc -l < "$d/$dll-$cpu.names") functions"
